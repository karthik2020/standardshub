export function getIconHtml(name: string): string {
  const iconDef = iconMap[name] || faBookOpen;
  const result = icon(iconDef);
  return result.html[0] ?? "";
}

export function getStandardIconHtml(code: string): string {
  const iconName = standardIcons[code] || fallbackIcon;
  return getIconHtml(iconName);
}

